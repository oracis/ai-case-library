# 正文书写约定：
# ("h1", 文本) / ("lead", 文本) / ("h2", 文本) / ("p", 文本)
# ("kv", 标签, 值)              —— 一组里最后一条写 ("kv!", 标签, 值) 收尾多留白
# ("foot", 文本)
# 正文里允许 <strong>，渲染时不做转义（本文件是源，不是用户输入）。


def render(blocks):
    out = ['<section style="%s">' % SECTION]
    for b in blocks:
        t = b[0]
        if t == 'h1':
            out.append('<h1 style="%s">%s</h1>' % (H1, b[1]))
        elif t == 'lead':
            out.append('<blockquote style="%s">%s</blockquote>' % (LEAD, b[1]))
        elif t == 'h2':
            out.append('<h2 style="%s">%s</h2>' % (H2, b[1]))
        elif t == 'p':
            out.append('<p style="%s">%s</p>' % (P, b[1]))
        elif t in ('kv', 'kv!'):
            st = KV_LAST if t == 'kv!' else KV
            out.append('<p style="%s"><span style="color:#57606a;">%s</span>：'
                       '<span style="color:#24292f;">%s</span></p>'
                       % (st, b[1], b[2]))
        elif t == 'foot':
            out.append('<p style="%s">%s</p>' % (FOOT, b[1]))
        else:
            raise SystemExit('未知段落类型 %r' % (t,))
    out.append('</section>')
    return '\n'.join(out) + '\n'


def count_cn(html):
    import re
    txt = re.sub(r'<[^>]+>', '', html)
    return len(re.findall(r'[\u4e00-\u9fff]', txt))


